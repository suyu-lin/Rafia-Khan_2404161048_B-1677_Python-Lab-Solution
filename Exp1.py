"""Demonstrate about fundamental Data types with suitable examples in Python Programming.
   (i.e., int, float, complex, bool and string types)"""
#Integer
a = 10
print(f"Type of a: {type(a)} \n a = {a}")
#Float
b = 10.5
print(f"Type of b: {type(b)} \n b = {b}")
#Complex
c = 2 + 3j
print(f"Type of c: {type(c)} \n c = {c}")
#Boolean
d = True
print(f"Type of d: {type(d)} \n d = {d}")
#String
e = "Hello, World!"
print(f"Type of e: {type(e)} \n e = {e}")

